// Действия, които телефонът има на няколко места (Управление, Настройка, Система): с потвърждение, както в телефона.
import { net, sendOrWarn } from '../net_ws.js';
import { fx, toast } from './ui.js';

const lastH = () => (net.st && net.st.h) || {};

export function centrStart() {
  if (confirm('Центриране: двете серва отиват точно в средата, 1500 µs.\n\nСвалени ли са главините (рамената) от двете серва? Иначе главата ще мръдне.'))
    sendOrWarn({ cmd: 'centrirane' });
}
export function centrDone() {
  const h = lastH();
  if (h.sm !== 'cent') { toast('Няма центриране в ход: първо „Центриране“', true); return; }
  if (confirm('Рамената сложени ли са обратно, точно както са били?\n\nТогава 1500 µs е мястото на заваряване и сервата се пускат, ограничени ±' + fx(h.capset, 1) + '°.'))
    sendOrWarn({ cmd: 'centrirani' });
}
/* Двете записват нула в паметта на главата: грешна нула мести защитата по ток, а грешен жироскоп наклона на
 * главата. Главата също отказва извън покой; питането е за ръката. */
export function curZeroGo() {
  if (confirm('Нула на тока: сегашният ток се записва като нула.\n\nСамо ако роботът е в покой, моторите и сервата са изключени и нищо не тегли ток. Иначе защитата по ток се измества.'))
    sendOrWarn({ cmd: 'curzero' });
}
export function himuCalGo() {
  if (confirm('Жироскоп на главата: калибровка около 2 s.\n\nГлавата да е неподвижна, а тялото в покой (не балансира).'))
    sendOrWarn({ cmd: 'himucal' });
}
